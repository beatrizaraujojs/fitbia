<script>
        document.addEventListener("DOMContentLoaded", () => {
            const faqItems = document.querySelectorAll('.faq-item');

            faqItems.forEach(item => {
                const perguntaBotao = item.querySelector('.faq-pergunta');
                const resposta = item.querySelector('.faq-resposta');

                // Se não achar o botão ou a resposta, ele ignora e não quebra o site
                if(!perguntaBotao || !resposta) return; 

                perguntaBotao.addEventListener('click', () => {
                    const isActive = item.classList.contains('ativo');

                    // Fecha as outras
                    faqItems.forEach(outroItem => {
                        outroItem.classList.remove('ativo');
                        if(outroItem.querySelector('.faq-resposta')) {
                            outroItem.querySelector('.faq-resposta').style.maxHeight = null;
                        }
                    });

                    // Abre a que foi clicada
                    if (!isActive) {
                        item.classList.add('ativo');
                        resposta.style.maxHeight = resposta.scrollHeight + "px";
                    }
                });
            });
        });
    </script>


<script>
function enviarParaWhatsApp() {
    // Pega os valores que o cliente digitou nos campos
    const nome = document.getElementById('zap-nome').value;
    const assunto = document.getElementById('zap-assunto').value;
    const mensagem = document.getElementById('zap-mensagem').value;
    
    // O número do seu WhatsApp (com código do país 55 e DDD)
    const telefone = "5511986210491"; 

    // Validação básica: avisa se a pessoa tentar enviar vazio
    if(!nome || !mensagem) {
        alert("Por favor, preencha pelo menos o seu nome e a mensagem antes de enviar!");
        return;
    }

    // Monta o texto bonitinho usando asteriscos para negrito no WhatsApp
    const texto = `Olá, Fit Bia! Me chamo *${nome}*.\n\n*Assunto:* ${assunto}\n\n*Mensagem:* ${mensagem}`;
    
    // Cria o link oficial do WhatsApp com o texto codificado
    const url = `https://wa.me/${telefone}?text=${encodeURIComponent(texto)}`;
    
    // Abre o WhatsApp em uma nova aba do navegador
    window.open(url, '_blank');
}
</script>



